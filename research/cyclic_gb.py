r"""Cyclic generalized-bicycle search stack over Z_m (prime m).

One module, two layers:

* **Construction** (bottom): the "designed-divisor" / "prime-lift" approach
  that produced the board's top kd^2/n codes (n ~ 670-680, k ~ 140-182,
  d ~ 64-90). n = 2m, H_X = [circ(a)|circ(b)], H_Z = [circ(b)^T|circ(a)^T],
  k = 2*deg(gcd(a, b, x^m-1)). Pick a divisor g(x) of x^m-1; draw a(x), b(x)
  as SPARSE codewords of the cyclic code with generator g(x) (multiples of
  g mod x^m-1), found by Prange search on the parity-check circulant.
* **Search** (divisor ideals -> fertile ideals -> build-and-screen), plus
  the board-advancing harness (dominance checks, deep confirmation, first
  advancing-code driver) and the sweep/find-advancing/confirm CLI.

Dependencies: research/kit/{css,surrogate}.py and the verify/ tree (both
committed upstream); numpy and sympy.

Provenance: this stack produced the generalized-bicycle wave merged in
PRs #1206-#1261 (hackathon #1155) and earlier GB records; distances are
upper bounds until the trusted gate (verify/validate_candidate.py) rules.
"""
