# ---------------------------------------------------------------------------
#  GF(2) polynomial helpers (coefficients little-endian: poly[0] = x^0 term)
# ---------------------------------------------------------------------------
def poly_mul(a, b):
    """Multiply two GF(2) polynomials (lists of 0/1, little-endian)."""
    r = [0] * (len(a) + len(b) - 1)
    for i, ai in enumerate(a):
        if ai:
            for j, bj in enumerate(b):
                r[i + j] ^= bj
    return r


def poly_mod(a, m):
    """a mod m over GF(2). m must be nonzero."""
    dm = len(m) - 1
    while dm > 0 and m[dm] == 0:
        dm -= 1
    m = m[: dm + 1]
    r = list(a)
    while len(r) >= len(m):
        shift = len(r) - len(m)
        if r[-1]:
            for j in range(len(m)):
                r[shift + j] ^= m[j]
        r.pop()
    return r


def poly_gcd(a, b):
    while any(b):
        a, b = b, poly_mod(a, b)
    return a


def poly_deg(a):
    d = len(a) - 1
    while d > 0 and a[d] == 0:
        d -= 1
    return d if (d > 0 or a[0]) else -1


def poly_to_int(a):
    v = 0
    for i, ai in enumerate(a):
        if ai:
            v |= (1 << i)
    return v


def int_to_poly(v, m=None):
    a = [int((v >> i) & 1) for i in range(v.bit_length())]
    if m is not None:
        a = a + [0] * (m - len(a))
    return a


# ---------------------------------------------------------------------------
#  Factor x^m - 1 over GF(2) via sympy
# ---------------------------------------------------------------------------
def factor_xn_minus_1(m):
    """Return the irreducible factors of x^m - 1 over GF(2), each as
    (poly_int, degree). poly_int is the integer encoding (little-endian)."""
    x = sympy.symbols("x")
    poly = sympy.Poly(x**m + 1, x, modulus=2)  # x^m - 1 == x^m + 1 over GF(2)
    factors = []
    for f, mult in sympy.factor_list(poly)[1]:
        coeffs = sympy.Poly(f, x, modulus=2).all_coeffs()[::-1]  # little-endian
        # normalize: strip leading zeros
        while len(coeffs) > 1 and coeffs[-1] == 0:
            coeffs.pop()
        p_int = poly_to_int(coeffs)
        deg = len(coeffs) - 1
        factors.append((p_int, deg))
    return factors


def poly_from_int(p_int, m):
    return int_to_poly(p_int, m)


# ---------------------------------------------------------------------------
#  Build a cyclic generalized-bicycle code
# ---------------------------------------------------------------------------
def circ(v):
    """Circulant matrix with first row v (length m)."""
    m = len(v)
    M = np.zeros((m, m), dtype=np.int8)
    for i in range(m):
        M[i] = np.roll(v, i)
    return M


def build_cyclic_gb(m, a, b):
    """Build HX, HZ for a cyclic generalized-bicycle code over Z_m.
    a, b are length-m 0/1 lists (the first-row supports of the circulants)."""
    A = circ(np.array(a, dtype=np.int8))
    B = circ(np.array(b, dtype=np.int8))
    HX = np.concatenate([A, B], axis=1)
    HZ = np.concatenate([B.T, A.T], axis=1)
    return HX, HZ


def k_from_ab(m, a, b):
    """k = 2 * deg(gcd(a(x), b(x), x^m - 1))."""
    xm1 = [1] + [0] * (m - 1) + [1]  # x^m + 1 = x^m - 1 over GF(2)
    g = poly_gcd(poly_gcd(a, b), xm1)
    return 2 * poly_deg(g)


# ---------------------------------------------------------------------------
#  Prange search: find sparse codewords in the ideal generated by g(x)
# ---------------------------------------------------------------------------
def parity_check_of_ideal(m, g_int):
    """Parity-check polynomial h = (x^m - 1)/g(x). Codewords of the cyclic
    code with generator g(x) are ker(circ(h))."""
    xm1 = [1] + [0] * (m - 1) + [1]
    g = int_to_poly(g_int, m)
    # trim trailing zeros of g down to its true degree
    while len(g) > 1 and g[-1] == 0:
        g.pop()
    gd = len(g) - 1
    # long division: h = (x^m - 1) / g
    h = [0] * (m + 1)
    rem = list(xm1)
    while poly_deg(rem) >= gd:
        shift = poly_deg(rem) - gd
        h[shift] = 1
        for j in range(len(g)):
            rem[shift + j] ^= g[j]
        # trim trailing zeros, keep at least length gd+1
        while len(rem) > gd + 1 and rem[-1] == 0:
            rem.pop()
    return h[:m]  # degree < m


def prange_sparse_words(m, g_int, weight_band, n_trials, seed=0, max_words=1000):
    """Find sparse codewords of the cyclic code with generator g(x) (i.e.
    sparse multiples of g(x) mod x^m - 1) via a randomized kernel search.

    Codewords are ker(circ(h)) where h = (x^m-1)/g(x). We take the kernel
    basis, then per trial do a random column permutation + RREF to get a
    different basis, and collect low-weight rows plus their pairwise sums.

    Returns a list of (support_tuple, weight) for distinct words found.
    """
    from css import kernel_basis
    h = parity_check_of_ideal(m, g_int)
    H = circ(np.array(h, dtype=np.int8))  # (m, m) parity check
    K = kernel_basis(H)  # rows span the codewords
    if K.size == 0:
        return []
    rng = np.random.default_rng(seed)
    words = {}
    lo, hi = weight_band
    for _ in range(n_trials):
        perm = rng.permutation(m)
        red = rref(K[:, perm])[0]
        w = red.sum(axis=1)
        # collect rows in band
        for i in np.where((w >= lo) & (w <= hi))[0]:
            v = np.zeros(m, dtype=np.int8)
            v[perm] = red[i]
            wt = int(v.sum())
            if lo <= wt <= hi:
                sup = tuple(sorted(np.where(v)[0]))
                if sup not in words:
                    words[sup] = wt
                    if len(words) >= max_words:
                        return list(words.items())
        # pairwise sums of the lightest rows (closes the gap to minima
        # realized only as short combinations)
        if red.shape[0] >= 2:
            light = np.argsort(w)[:min(10, red.shape[0])]
            sub = red[light]
            for i in range(len(light)):
                pr = (sub[i] + sub[i + 1:]) % 2
                if pr.size == 0:
                    continue
                pw = pr.sum(axis=1)
                for j in np.where((pw >= lo) & (pw <= hi))[0]:
                    v = np.zeros(m, dtype=np.int8)
                    v[perm] = pr[j]
                    wt = int(v.sum())
                    if lo <= wt <= hi:
                        sup = tuple(sorted(np.where(v)[0]))
                        if sup not in words:
                            words[sup] = wt
                            if len(words) >= max_words:
                                return list(words.items())
    return list(words.items())


